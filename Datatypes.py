#String
s="Welcome to Python World"
print(s)
print(type(s))

#int
i=26
print(i)
print(type(i))

#float
f=26.28
print(f)
print(type(f))

#complex
c=6j
print(c)
print(type(c))

#boolean
b=True
print(b)
print(type(b))

#list
l=[10,20,30,40]
print(l)
print(type(l))

#tuple
t=(80,50,30,60)
print(t)
print(type(t))

#range
x=range(6)
print(range(6))
print(type(x))

#dictionary
dic={"Name":"Sanika", "Age":20}
print(dic)
print(type(dic))

#set
fruits={"Apple","Banana","Kiwi"}
print(fruits)
print(type(fruits))

#frozenset
fr=({10,20,30,40})
print(fr)
print(type(fr))

#bytes
data=b"Hello"
print(data)
print(type(data))

#bytearray
data1=bytearray(5)
print(data1)
print(type(data1))

#memoryview
view=memoryview(bytes(6))
print(view)
print(type(view))

#None type
n=None
print(n)
print(type(n))
